#!/usr/bin/env node
/* eslint-disable no-console */

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const SERVICE = process.argv[2];

if (!SERVICE) {
  console.error('');
  console.error('Usage:');
  console.error('');
  console.error('node tools/codegen/01-create-service.js identity');
  console.error('');
  process.exit(1);
}

const ROOT = process.cwd();

const APP_NAME = `${SERVICE}-service`;

const APP_PATH = path.join(ROOT, 'apps', APP_NAME);

/**
 * --------------------------------------------------------
 * Validate NX Workspace
 * --------------------------------------------------------
 */

const nxJson = path.join(ROOT, 'nx.json');

if (!fs.existsSync(nxJson)) {
  console.error('');
  console.error('❌ Current directory is not an NX workspace.');
  console.error('');
  process.exit(1);
}

/**
 * --------------------------------------------------------
 * Existing project?
 * --------------------------------------------------------
 */

if (fs.existsSync(APP_PATH)) {
  console.error('');
  console.error(`❌ ${APP_NAME} already exists.`);
  console.error('');
  process.exit(1);
}

console.log('');
console.log('==========================================');
console.log('🚀 Creating Microservice');
console.log('==========================================');
console.log('');

console.log(`Service : ${SERVICE}`);
console.log(`Project : ${APP_NAME}`);
console.log('');

const command = process.platform === 'win32' ? 'npx.cmd' : 'npx';

const args = [
  'nx',

  'g',

  '@nx/node:application',

  APP_NAME,

  `--directory=apps/${APP_NAME}`,

  '--framework=none',

  '--bundler=esbuild',

  '--routing=false',

  '--strict',

  '--linter=eslint',

  '--unitTestRunner=jest',

  '--e2eTestRunner=none',

  '--projectNameAndRootFormat=as-provided',

  `--tags=type:microservice,scope:${SERVICE}`,
];

const result = spawnSync(command, args, {
  cwd: ROOT,
  stdio: 'inherit',
});

if (result.status !== 0) {
  console.error('');
  console.error('❌ Failed to create service.');
  console.error('');
  process.exit(result.status);
}

/**
 * --------------------------------------------------------
 * README
 * --------------------------------------------------------
 */

createReadme();

/**
 * --------------------------------------------------------
 */

console.log('');
console.log('==========================================');
console.log('✅ Service Created Successfully');
console.log('==========================================');
console.log('');

console.log(APP_PATH);
console.log('');

/**
 * --------------------------------------------------------
 */

function createReadme() {
  const content = `# ${APP_NAME}

Generated by the Microservice Code Generator.

## Service

${SERVICE}

## Status

Bootstrap Completed

## Next Step

Run

\`\`\`bash
node tools/codegen/02-create-folder-structure.js ${SERVICE}
\`\`\`

`;

  fs.writeFileSync(path.join(APP_PATH, 'README.md'), content, 'utf8');
}
